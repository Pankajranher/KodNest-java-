public class If_else_to_switch {
    public static void main(String[] args) {
        int day = 6;
        switch (day) {
            case 1:
                System.out.println("Learning Day");
                break;

            case 2:
                System.out.println("Learning Day");
                break;

            case 3:
                System.out.println("Learning Day");
                break;

            case 4:
                System.out.println("Learning Day");
                break;

            case 5:
                System.out.println("Learning Day");
                break;

            case 6:
                System.out.println("Revision Day");
                break;

            case 7:
                System.out.println("Revision Day");
                break;

            default:
                System.out.println("Invalid Day");
        }
    }
}
